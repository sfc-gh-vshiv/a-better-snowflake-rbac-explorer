-- Role Explorer: demo scenario for protected-role alerts (idempotent). Run as ACCOUNTADMIN.
--   snow sql -c <connection> -f setup/demo_seed.sql -D warehouse=<WAREHOUSE> -D alert_email=<you@company.com>
-- A service role meant only for one SERVICE user, plus a PERSON user to "accidentally" grant it to.
-- Clean up with: DROP USER DEMO_ANALYST_JANE; DROP USER DEMO_PIPELINE_SVC; DROP ROLE DEMO_PIPELINE_SVC_ROLE;
--                DELETE FROM RBAC_EXPLORER_DB.ALERTS.PROTECTED_ROLES WHERE ROLE_NAME = 'DEMO_PIPELINE_SVC_ROLE';
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DEMO_PIPELINE_SVC_ROLE COMMENT = 'Role Explorer demo: ingestion service role, SERVICE users only';
GRANT ROLE DEMO_PIPELINE_SVC_ROLE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE IDENTIFIER('<% warehouse %>') TO ROLE DEMO_PIPELINE_SVC_ROLE;

CREATE USER IF NOT EXISTS DEMO_PIPELINE_SVC TYPE = SERVICE DEFAULT_ROLE = DEMO_PIPELINE_SVC_ROLE
  COMMENT = 'Role Explorer demo: pipeline service user (no credentials)';
CREATE USER IF NOT EXISTS DEMO_ANALYST_JANE TYPE = PERSON
  COMMENT = 'Role Explorer demo: a person who must never hold the service role (no credentials)';
GRANT ROLE DEMO_PIPELINE_SVC_ROLE TO USER DEMO_PIPELINE_SVC;

-- The rule: only DEMO_PIPELINE_SVC, only SERVICE users, only inherited by SYSADMIN.
INSERT INTO RBAC_EXPLORER_DB.ALERTS.PROTECTED_ROLES (ROLE_NAME, ALLOWED_USERS, ALLOWED_USER_TYPE, ALLOWED_PARENT_ROLES,
  NOTIFY_EMAIL, NOTIFY_SLACK, AUTO_REVOKE, ENABLED, NOTE, CREATED_BY)
SELECT 'DEMO_PIPELINE_SVC_ROLE', ARRAY_CONSTRUCT('DEMO_PIPELINE_SVC'), 'SERVICE', ARRAY_CONSTRUCT('SYSADMIN'),
       '<% alert_email %>', FALSE, FALSE, TRUE, 'Demo: ingestion service account only', CURRENT_USER()
WHERE NOT EXISTS (SELECT 1 FROM RBAC_EXPLORER_DB.ALERTS.PROTECTED_ROLES WHERE ROLE_NAME = 'DEMO_PIPELINE_SVC_ROLE');
